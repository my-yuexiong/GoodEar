# ============================================================
# 音频捕获参数
# ============================================================

# WASAPI loopback 捕获参数
# 采样率会自动从默认设备检测，此值为回退默认
SAMPLE_RATE = 48000
CHANNELS = 2                  # 立体声
CHUNK_SIZE = 1024             # 每帧采样数 (~21ms @ 48kHz)
FORMAT_BITS = 16              # 位深度

# 缓冲区
BUFFER_CHUNKS = 8             # 环形缓冲区中保留的最近 chunk 数
PROCESS_WINDOW = 4096 * 4     # 处理窗口大小 (~341ms @ 48kHz)

# ============================================================
# 方向估算参数
# ============================================================

# ITD 最大时延 (秒)
# 人头直径 ~0.175m，声速 343m/s → 0.51ms
# 游戏引擎 HRTF 可能产生更大的虚拟时延，设宽一点
MAX_TAU = 0.00065             # 0.65ms

# GCC-PHAT 参数
GCC_INTERP = 16               # 插值倍数，提高时延精度
GCC_MAX_TAU = 0.00065         # 搜索范围限制

# 融合权重 (ITD:ILD)
ITD_WEIGHT = 0.6
ILD_WEIGHT = 0.4

# ILD 映射参数
MAX_ILD_DB = 15.0             # 声道极值对应的 dB 差

# ============================================================
# 脚步声检测参数
# ============================================================

# 带通滤波器
BP_LOW = 200                  # 低频截止 (Hz)
BP_HIGH = 800                 # 高频截止 (Hz)
BP_ORDER = 4                  # Butterworth 阶数

# 高频辅助频段
HF_LOW = 2000                 # Hz
HF_HIGH = 4000                # Hz

# Spectral Flux onset 检测
FFT_FRAME_SIZE = 1024         # FFT 窗口大小
FFT_HOP_SIZE = 512            # 滑动步长
FLUX_HISTORY_SIZE = 300       # 通量历史长度 (约 3.2s @ 48kHz+512hop)
FLUX_THRESHOLD_K = 2.5        # threshold = median + k * MAD * 1.4826

# 防抖 (最小 onset 间隔)
MIN_ONSET_SEC = 0.12          # 120ms
MIN_ONSET_FRAMES = int(MIN_ONSET_SEC * SAMPLE_RATE / FFT_HOP_SIZE)

# ============================================================
# 声音分类参数
# ============================================================

# 频谱质心阈值
GUNSHOT_CENTROID_MIN = 3000   # 枪声质心下限 (Hz)
FOOTSTEP_CENTROID_MAX = 2000  # 脚步质心上限 (Hz)

# 持续时间阈值
GUNSHOT_DURATION_MAX = 0.05   # 枪声最长持续时间 (秒)
EXPLOSION_DURATION_MIN = 0.2  # 爆炸最短持续时间 (秒)

# 频段能量比阈值
EXPLOSION_BASS_RATIO_MIN = 0.5

# ============================================================
# 距离估算参数
# ============================================================

REF_AMP_DB = -18.0            # 参考距离处的 RMS dB (需校准)
REF_DIST_M = 5.0              # 参考距离 (米)
MAX_DIST_M = 50.0             # 最大可检测距离 (米)
DB_PER_DOUBLING = 6.0         # 距离翻倍对应 dB 衰减

# ============================================================
# 雷达显示参数
# ============================================================

RADAR_SIZE = 600              # 窗口尺寸 (像素)
RADAR_FPS = 30                # 目标帧率
SWEEP_SPEED = 120             # 扫描线旋转速度 (度/秒)
POINT_LIFETIME = 3.0          # 检测点存活时间 (秒)
TRAIL_FADE_SPEED = 8          # 拖尾每帧衰减量 (alpha 值)

# 颜色
BG_COLOR = (0, 0, 0)
